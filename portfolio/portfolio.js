/* Functions */
function shuffle(array) {
    for (let i = array.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [array[i], array[j]] = [array[j], array[i]];
    }
    return array;
}

function populateGalleryColumns() {
    const firstGalleryColumn = document.createDocumentFragment();
    const secondGalleryColumn = document.createDocumentFragment();
    const thirdGalleryColumn = document.createDocumentFragment();

    const totalImages = listEventsImages.length + listPortraitImages.length;
    const firstDivisionIndex = Math.floor(totalImages / 3 - 1);
    const secondDivisionIndex = Math.floor(firstDivisionIndex * 2 - 1);
    const thirdDivisionIndex = Math.floor(firstDivisionIndex * 3 - 1);

    for (let imageIndex = 0; imageIndex < firstDivisionIndex; imageIndex++) {
        const image = listAllImages[imageIndex];
        const img = document.createElement('img');
        img.src = image.src;
        img.classList.add(image.category);
        img.addEventListener('click', () => setLightboxImage(img));
        firstGalleryColumn.appendChild(img);
    }

    for (let imageIndex = firstDivisionIndex; imageIndex < secondDivisionIndex; imageIndex++) {
        const image = listAllImages[imageIndex];
        const img = document.createElement('img');
        img.src = image.src;
        img.classList.add(image.category);
        img.addEventListener('click', () => setLightboxImage(img));
        secondGalleryColumn.appendChild(img);
    }

    for (let imageIndex = secondDivisionIndex; imageIndex < thirdDivisionIndex; imageIndex++) {
        const image = listAllImages[imageIndex];
        const img = document.createElement('img');
        img.src = image.src;
        img.classList.add(image.category);
        img.addEventListener('click', () => setLightboxImage(img));
        thirdGalleryColumn.appendChild(img);
    }

    const firstColumnDiv = document.getElementById('gallery-column-1');
    const secondColumnDiv = document.getElementById('gallery-column-2');
    const thirdColumnDiv = document.getElementById('gallery-column-3');

    firstColumnDiv.appendChild(firstGalleryColumn);
    secondColumnDiv.appendChild(secondGalleryColumn);
    thirdColumnDiv.appendChild(thirdGalleryColumn);
}

function addClassDisplay(className) {
    const listAllImageElements = [
        ...document.querySelectorAll('#gallery-column-1 img'),
        ...document.querySelectorAll('#gallery-column-2 img'),
        ...document.querySelectorAll('#gallery-column-3 img')
    ];

    listAllImageElements.forEach(element => {
        const hasClassName = element.classList.contains(className);

        const isAllTabSelected = className === classAll;

        const shouldRemoveClassHide =
            hasClassName ||
            isAllTabSelected;

        if (shouldRemoveClassHide) {
            element.classList.remove(classHide);
        } else {
            element.classList.add(classHide);
        }
    })
}

function addTabEventListener(id, event) {
    document.addEventListener("DOMContentLoaded", function() {
        const button = document.getElementById(id);

        button.addEventListener("click", event);
    });
}

function showAllImages() {
    addClassDisplay(classAll);
}

function showPortraitureImages() {
    addClassDisplay(classPortraiture);
}

function showEventImages() {
    addClassDisplay(classEvents);
}

function showVenueImages() {
    addClassDisplay(classVenue);
}

function showStreetImages() {
    addClassDisplay(classStreet);
}

function addAllTabEventListeners() {
    if (!hasAddedEventListeners) {
        addTabEventListener(idAllTab, showAllImages);
        addTabEventListener(idPortraitureTab, showPortraitureImages);
        addTabEventListener(idEventTab, showEventImages);
        addTabEventListener(idVenueTab, showVenueImages);
        addTabEventListener(idStreetTab, showStreetImages);
    }

    hasAddedEventListeners = true;
}

const lightbox = document.getElementById('lightbox');
const navigationBar = document.getElementById('navigation-bar');

function setLightboxImage(img) {
    const lightboxImage = document.getElementById('lightbox-image');

    lightboxImage.src = img.dataset.full || img.src;
    lightboxImage.alt = img.alt;

    lightbox.classList.add('active');
    navigationBar.classList.add('lightbox-active');
}

function setLightboxCloseClickEventListener() {
    document.querySelector('.lightbox-close').addEventListener('click', () => {
        lightbox.classList.remove('active');
        navigationBar.classList.remove('lightbox-active');
    });
}

function setLightboxBackDropClickEventListener() {
    lightbox.addEventListener('click', (e) => {
        if (e.target === lightbox) {
            lightbox.classList.remove('active');
            navigationBar.classList.remove('lightbox-active');
        }
    });
}

function setLightboxEscapeKeydownEventListener() {
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && lightbox.classList.contains('active')) {
            lightbox.classList.remove('active');
            navigationBar.classList.remove('lightbox-active');
        }
    });
}

function setLightboxCloseEventListeners() {
   setLightboxCloseClickEventListener();
   setLightboxBackDropClickEventListener()
   setLightboxEscapeKeydownEventListener();
}

